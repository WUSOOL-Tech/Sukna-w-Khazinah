#!/usr/bin/env python3
"""Generate platform files from brand/design-system/tokens.json.

Outputs (brand/design-system/):
  tokens.css           CSS custom properties (--sk-*)
  tailwind.preset.js   Tailwind CSS preset
  tokens.flat.json     Flat key → value map (for Figma Tokens / scripts)
  contrast-report.md   WCAG 2.2 contrast for every text/background pairing we allow
Usage: python3 scripts/build_tokens.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DS = os.path.join(ROOT, "brand/design-system")
tokens = json.load(open(os.path.join(DS, "tokens.json")))


def flatten(node, prefix=()):
    out = {}
    for k, v in node.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" in v:
            out[".".join(prefix + (k,))] = v
        elif isinstance(v, dict):
            out.update(flatten(v, prefix + (k,)))
    return out


flat = flatten(tokens)


def resolve(value):
    if isinstance(value, str):
        m = re.fullmatch(r"\{([^}]+)\}", value)
        if m:
            return resolve(flat[m.group(1)]["$value"])
    return value


def css_value(tok):
    v, t = resolve(tok["$value"]), tok.get("$type")
    if t == "fontFamily":
        return ", ".join(f'"{f}"' if " " in f else f for f in v)
    if t == "cubicBezier":
        return "cubic-bezier(%s)" % ", ".join(str(x) for x in v)
    if t == "number" and "angle" in tok.get("_path", ""):
        return f"{v}deg"
    return str(v)


def var_name(path):
    return "--sk-" + path.replace(".", "-")


lines = ["/* Generated by scripts/build_tokens.py from tokens.json — do not edit by hand. */", ":root {"]
for path, tok in flat.items():
    tok["_path"] = path
    raw = tok["$value"]
    ref = re.fullmatch(r"\{([^}]+)\}", raw) if isinstance(raw, str) else None
    value = f"var({var_name(ref.group(1))})" if ref else css_value(tok)
    lines.append(f"  {var_name(path)}: {value};")
lines.append("}")
lines.append("")
lines.append("@media (prefers-reduced-motion: reduce) {")
lines.append("  :root {")
for path in flat:
    if path.startswith("motion.duration") or path.startswith("motion.stagger"):
        lines.append(f"    {var_name(path)}: 0ms;")
lines.append("  }")
lines.append("}")
open(os.path.join(DS, "tokens.css"), "w").write("\n".join(lines) + "\n")

json.dump({k: resolve(v["$value"]) for k, v in flat.items()}, open(os.path.join(DS, "tokens.flat.json"), "w"),
          ensure_ascii=False, indent=2)


# Tailwind preset
def group(prefix):
    return {k[len(prefix) + 1:].replace(".", "-"): f"var({var_name(k)})" for k in flat if k.startswith(prefix + ".")}


preset = {
    "theme": {
        "extend": {
            "colors": {
                "brand": group("color.brand"),
                "green": group("color.green"),
                "yellow": group("color.yellow"),
                "neutral": group("color.neutral"),
                "status": group("color.status"),
                "sk": group("color.semantic"),
            },
            "fontFamily": {k: resolve(flat[f"font.family.{k}"]["$value"]) for k in ("display", "text", "numeric")},
            "fontSize": group("font.size"),
            "spacing": group("space"),
            "borderRadius": group("radius"),
            "boxShadow": group("shadow"),
            "transitionDuration": group("motion.duration"),
            "transitionTimingFunction": group("motion.easing"),
            "screens": {k[len("breakpoint."):]: resolve(v["$value"]) for k, v in flat.items() if k.startswith("breakpoint.")},
        }
    }
}
open(os.path.join(DS, "tailwind.preset.js"), "w").write(
    "// Generated by scripts/build_tokens.py — import tokens.css once, then:\n"
    "// module.exports = { presets: [require('./brand/design-system/tailwind.preset.js')], ... }\n"
    "module.exports = " + json.dumps(preset, ensure_ascii=False, indent=2) + ";\n"
)


# Contrast report
def lum(h):
    h = h.lstrip("#")
    c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


def grade(r):
    if r >= 7:
        return "AAA"
    if r >= 4.5:
        return "AA"
    if r >= 3:
        return "AA large / graphics"
    return "✗ logo & decoration only"


C = lambda p: resolve(flat[p]["$value"])
fgs = [("Ink", "color.brand.ink"), ("Deep Green", "color.brand.deep"), ("Green 700", "color.green.700"),
       ("Neutral 600", "color.neutral.600"), ("Neutral 500", "color.neutral.500"), ("Sukna Green", "color.brand.green"),
       ("Khazinah Yellow", "color.brand.yellow"), ("White", "color.brand.white")]
bgs = [("White", "color.brand.white"), ("Paper", "color.brand.paper"), ("Khazinah Yellow", "color.brand.yellow"),
       ("Sukna Green", "color.brand.green"), ("Ink", "color.brand.ink")]
rows = ["# Contrast report (WCAG 2.2)", "", "Generated by `scripts/build_tokens.py`. Body text needs **AA (4.5:1)**; "
        "text ≥ 24px or bold ≥ 18.66px needs 3:1. The logo itself is exempt, but the rules below still apply to any text near it.", "",
        "| Text ↓ / Background → | " + " | ".join(f"{n} `{C(p)}`" for n, p in bgs) + " |",
        "|---|" + "---|" * len(bgs)]
for fn, fp in fgs:
    cells = []
    for bn, bp in bgs:
        if fp == bp:
            cells.append("—")
            continue
        r = ratio(C(fp), C(bp))
        cells.append(f"{r:.2f} {grade(r)}")
    rows.append(f"| {fn} `{C(fp)}` | " + " | ".join(cells) + " |")
rows += ["", "**Key rules**", "",
         f"- Sukna Green on Khazinah Yellow is {ratio(C('color.brand.green'), C('color.brand.yellow')):.2f}:1 — reserved for the logo and large graphic shapes, never for reading text.",
         "- On Sukna Green, set all text in Ink. On Khazinah Yellow, use Ink or Deep Green.",
         "- White text is not used on Sukna Green or Khazinah Yellow."]
open(os.path.join(DS, "contrast-report.md"), "w").write("\n".join(rows) + "\n")
print(f"{len(flat)} tokens → tokens.css, tailwind.preset.js, tokens.flat.json, contrast-report.md")
