#!/usr/bin/env node
/* Build the logo-reveal page and render it to MP4/GIF/PNG frames.
 *
 *   NODE_PATH=$(npm root -g) node scripts/render_motion.cjs
 *
 * Needs: playwright (Chromium) and ffmpeg on PATH.
 * Writes brand/motion/logo-reveal.html (self-contained, plays in any browser)
 * and brand/motion/renders/*.mp4|gif|png.
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..");
const MOTION = path.join(ROOT, "brand/motion");
const RENDERS = path.join(MOTION, "renders");
const master = JSON.parse(fs.readFileSync(path.join(ROOT, "brand/logo/master/sukna-w-khazinah_master.json"), "utf8"));

// Path indices in the master geometry, grouped by role.
const ROLE = {
  sukna: [0], suknaDots: [10, 16, 15],
  waw: [3], wawRules: [4, 6],
  khazinah: [2, 1], khazinahDots: [9, 8, 17, 12, 11, 14, 13],
  underRules: [7, 5],
};

const W = master.width, H = master.height;
const paths = master.paths.map((d, i) => `<path id="p${i}" d="${d}"/>`).join("\n      ");

const html = `<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>سكنة وخزينة — Logo Reveal</title>
<!-- Generated by scripts/render_motion.cjs. Timeline spec: brand/motion/README.md -->
<style>
  :root { --bg: #F0FF0B; --fg: #02C277; }
  html, body { margin: 0; height: 100%; }
  body { display: grid; place-items: center; background: var(--bg); overflow: hidden; font-family: system-ui, sans-serif; }
  body.reverse { --bg: #02C277; --fg: #F0FF0B; }
  svg { width: min(56vw, 120vh); height: auto; overflow: visible; }
  svg path { fill: var(--fg); transform-box: fill-box; }
  .rule { transform-origin: right center; }
  .dot { transform-origin: center; }
  .controls { position: fixed; inset-block-end: 16px; inset-inline-start: 16px; display: flex; gap: 8px; }
  .controls button { font: 600 14px/1 system-ui, sans-serif; padding: 10px 14px; border: 2px solid #0B2A1E; background: transparent; color: #0B2A1E; cursor: pointer; }
  body.capture .controls { display: none; }
</style>
</head>
<body>
  <svg viewBox="0 0 ${W.toFixed(2)} ${H.toFixed(2)}" role="img" aria-label="سكنة وخزينة">
      ${paths}
  </svg>
  <div class="controls">
    <button id="replay">إعادة ▶</button>
    <button id="swap">تبديل الخلفية</button>
  </div>
<script>
const ROLE = ${JSON.stringify(ROLE)};
// Motion tokens (brand/design-system/tokens.json → motion.*)
const EASE = {
  ascend: "cubic-bezier(0.16, 1, 0.3, 1)",
  draw:   "cubic-bezier(0.65, 0, 0.35, 1)",
  pop:    "cubic-bezier(0.34, 1.56, 0.64, 1)",
};
const ASCENT = { x: -60, y: 7.9 };   // 60 units along the 7.5° line
const TOTAL = 3200;                    // 2400 ms reveal + 800 ms hold

const $ = i => document.getElementById("p" + i);
ROLE.wawRules.concat(ROLE.underRules).forEach(i => $(i).classList.add("rule"));
ROLE.suknaDots.concat(ROLE.khazinahDots).forEach(i => $(i).classList.add("dot"));

function ascend(i, delay, dur = 700) {
  $(i).animate([
    { opacity: 0, transform: \`translate(\${ASCENT.x}px, \${ASCENT.y}px)\` },
    { opacity: 1, transform: "translate(0, 0)" }
  ], { duration: dur, delay, easing: EASE.ascend, fill: "both" });
}
function draw(i, delay, dur = 600) {
  $(i).animate([{ transform: "scaleX(0)" }, { transform: "scaleX(1)" }],
    { duration: dur, delay, easing: EASE.draw, fill: "both" });
}
function pop(i, delay, dur = 260) {
  $(i).animate([{ opacity: 0, transform: "scale(0)" }, { opacity: 1, transform: "scale(1)" }],
    { duration: dur, delay, easing: EASE.pop, fill: "both" });
}
function drop(i, delay, dur = 420) {
  $(i).animate([{ opacity: 0, transform: "translateY(-24px)" }, { opacity: 1, transform: "translateY(0)" }],
    { duration: dur, delay, easing: EASE.pop, fill: "both" });
}

function build() {
  document.getAnimations().forEach(a => a.cancel());
  // LINES LEAD — the two rules around «و» draw first (right → left).
  ROLE.wawRules.forEach((i, k) => draw(i, k * 120));
  // BEAT 1 — «سكنة» ascends, its dots land.
  ROLE.sukna.forEach(i => ascend(i, 150));
  ROLE.suknaDots.forEach((i, k) => pop(i, 650 + k * 70));
  // The connector «و» drops between the rules.
  ROLE.waw.forEach(i => drop(i, 850));
  // PAUSE, then BEAT 2 — «خزينة» ascends, its dots land.
  ROLE.khazinah.forEach((i, k) => ascend(i, 1150 + k * 80));
  ROLE.underRules.forEach((i, k) => draw(i, 1450 + k * 120));
  ROLE.khazinahDots.forEach((i, k) => pop(i, 1650 + k * 70));
}

window.seek = ms => document.getAnimations().forEach(a => { a.pause(); a.currentTime = ms; });
window.TOTAL = TOTAL;

const params = new URLSearchParams(location.search);
if (params.get("bg") === "green") document.body.classList.add("reverse");
if (params.has("capture")) document.body.classList.add("capture");
build();
if (params.has("capture")) seek(0);
else if (matchMedia("(prefers-reduced-motion: reduce)").matches) seek(TOTAL);

document.getElementById("replay").onclick = build;
document.getElementById("swap").onclick = () => { document.body.classList.toggle("reverse"); build(); };
</script>
</body>
</html>
`;

fs.mkdirSync(RENDERS, { recursive: true });
const htmlPath = path.join(MOTION, "logo-reveal.html");
fs.writeFileSync(htmlPath, html);

(async () => {
  const FPS = 30;
  const browser = await chromium.launch();
  const jobs = [
    { name: "logo-reveal_yellow_1920x1080", bg: "yellow", w: 1920, h: 1080 },
    { name: "logo-reveal_green_1920x1080", bg: "green", w: 1920, h: 1080 },
    { name: "logo-reveal_yellow_1080x1920", bg: "yellow", w: 1080, h: 1920 },
  ];
  for (const job of jobs) {
    const page = await browser.newPage({ viewport: { width: job.w, height: job.h } });
    await page.goto("file://" + htmlPath + "?capture&bg=" + job.bg);
    const total = await page.evaluate(() => window.TOTAL);
    const frames = path.join(RENDERS, ".frames-" + job.name);
    fs.rmSync(frames, { recursive: true, force: true });
    fs.mkdirSync(frames);
    const n = Math.round((total / 1000) * FPS);
    for (let f = 0; f <= n; f++) {
      await page.evaluate(ms => window.seek(ms), (f * 1000) / FPS);
      await page.screenshot({ path: path.join(frames, String(f).padStart(4, "0") + ".png") });
    }
    if (job.bg === "yellow" && job.w === 1920) {
      fs.copyFileSync(path.join(frames, String(n).padStart(4, "0") + ".png"), path.join(RENDERS, "logo-reveal_end-frame.png"));
      for (const [label, ms] of [["01", 300], ["02", 800], ["03", 1300], ["04", 1900], ["05", 2600]]) {
        await page.evaluate(t => window.seek(t), ms);
        await page.screenshot({ path: path.join(RENDERS, `storyboard-${label}_${ms}ms.png`) });
      }
    }
    await page.close();
    const mp4 = path.join(RENDERS, job.name + ".mp4");
    execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-framerate", String(FPS), "-i", path.join(frames, "%04d.png"),
      "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-movflags", "+faststart", mp4]);
    if (job.w === 1920) {
      const gif = path.join(RENDERS, job.name.replace("1920x1080", "800w") + ".gif");
      execFileSync("ffmpeg", ["-y", "-loglevel", "error", "-framerate", String(FPS), "-i", path.join(frames, "%04d.png"),
        "-vf", "fps=25,scale=800:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=32[p];[b][p]paletteuse=dither=none",
        gif]);
    }
    fs.rmSync(frames, { recursive: true, force: true });
    console.log("rendered", job.name);
  }
  await browser.close();
})();
